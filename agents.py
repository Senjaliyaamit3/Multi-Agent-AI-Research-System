from langchain.agents import create_agent
from langchain_mistralai import ChatMistralAI
from langchain_core.prompts import ChatPromptTemplate
from langchain_core.output_parsers import StrOutputParser
from tools import web_search, scrape_url
from dotenv import load_dotenv

load_dotenv()

# model setup
llm = ChatMistralAI(
    model = "mistral-small-latest",
    temperature = 0
)

# 1st Agent
def build_search_agent():
    return create_agent(
        model = llm,
        tools = [web_search]
    )

# 2nd Agent 
def build_reader_agent():
    return create_agent(
        model = llm,
        tools = [scrape_url]
    )

# Writer Chain

writer_prompt = ChatPromptTemplate.from_messages([
    ("system","You are an expert research writer. Write clear, structured and insightful reports."),
    ("human","""Write a detaild researchl report on the topic below.
    
    Topic: {topic}
    Research Gathered:
    {research}

    Structure the report as:
    - Introduction
    - Key Findings (minimum 3 well-explained points)
    - Conclusion
    - Sources (list all URLs found in the research)

    Be detailed, factual and professional.""")
])

writer_chain = writer_prompt | llm | StrOutputParser()

# critic_chain

critic_prompt = ChatPromptTemplate.from_messages([
    (
        "system",
        """You are an expert research critic and fact-checker.

        Your job is to critically evaluate a research report generated by another
        research agent.

        Analyze the report carefully and identify:

        1. Factual inaccuracies or potentially incorrect claims.
        2. Unsupported claims that are not backed by the provided research.
        3. Missing important information or perspectives.
        4. Weak, unclear, repetitive, or poorly explained points.
        5. Problems with the structure, clarity, and logical flow.
        6. Whether the conclusions are actually supported by the research.
        7. Whether the listed sources are relevant and sufficient.
        8. Any possible hallucinations or assumptions made by the writer.

        Do not rewrite the entire report.

        Instead, provide clear and actionable feedback that another writer agent
        can use to improve the report.

        If the report is already strong, explicitly mention what is good and
        only suggest improvements that are genuinely necessary."""
            ),

        (
            "human",
            """Critically review the following research report.

            Topic:
            {topic}

            Research Gathered:
            {research}

            Research Report:
            {report}

            Evaluate the report using the following criteria:

            - Accuracy
            - Completeness
            - Relevance
            - Source quality
            - Logical reasoning
            - Clarity
            - Structure
            - Unsupported claims / hallucinations
            - Quality of conclusion

            Return your review in this format:

            ## Overall Assessment
            Give a brief overall evaluation of the report.

            ## Strengths
            List the strongest parts of the report.

            ## Issues Found
            List factual errors, unsupported claims, missing information,
            weak reasoning, or structural problems.

            ## Missing Information
            Mention important information that should be added.

            ## Recommended Improvements
            Give specific and actionable suggestions for improving the report.

            ## Final Verdict
            Classify the report as one of:
            - PASS
            - NEEDS_REVISION
            - MAJOR_REVISION

            Be objective, factual, and critical. Do not rewrite the complete report."""
            )
        ])

critic_chain = critic_prompt | llm | StrOutputParser()